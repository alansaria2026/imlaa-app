/// الكلمة مشكولة للنطق، مع (الـ) إن وُجدت: سكون على اللام القمرية،
/// وشدة على الحرف الذي يلي اللام الشمسية.
String spokenForm(String word) {
  final w = stripDiacritics(word);
  final hasAl = w.startsWith('ال');
  final bare = hasAl ? w.substring(2) : w;
  final v = _voweled[bare];
  if (v == null) return word;
  if (!hasAl) return v;
  if (lamTypeOf(bare) == LamType.moon) return 'الْ$v';
  final rest = v.substring(1);
  return 'ال${v[0]}${rest.startsWith('ّ') ? '' : 'ّ'}$rest';
}
